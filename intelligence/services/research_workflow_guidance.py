def workflow_guidance(question_type: str) -> str:
    """Use the resolved question type; do not infer a second route from text."""
    if os.environ.get(ENV_FLAG, "1").strip().lower() in {"0", "off", "false", "no"}:
        return ""
    rules = _RULES.get(question_type)
    if not rules:
        return ""
    boundary = (
        "仅在本轮材料范围和已授权工具内执行；缺失资料明确降级，不能扩大读取权限。"
        "下面是分析纪律，不是已有事实或审查通过证明；仍按本轮输出槽和证据绑定契约交付。"
    )
    return "\n\n" + HEADING + "\n" + boundary + "\n" + "\n".join(rules)
